const language = (() => {
  const requested = new URLSearchParams(location.search).get('lang');
  if (requested === 'ar' || requested === 'en') {
    try { localStorage.setItem('almushref.language', requested); } catch { /* Storage is optional. */ }
    return requested;
  }
  try { return localStorage.getItem('almushref.language') === 'ar' ? 'ar' : 'en'; }
  catch { return 'en'; }
})();
const isArabic = language === 'ar';
const t = (english) => isArabic ? (arabic[english] ?? english) : english;
const localText = (english, translation) => isArabic ? translation : english;
const siteLink = (href) => {
  if (!isArabic) return href;
  const url = new URL(href, location.href);
  url.searchParams.set('lang', 'ar');
  return url.href;
};

document.documentElement.lang = isArabic ? 'ar-AE' : 'en';
document.documentElement.dir = isArabic ? 'rtl' : 'ltr';

if (isArabic) {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const text = node.nodeValue.trim();
    if (Object.hasOwn(arabic, text)) node.nodeValue = node.nodeValue.replace(text, arabic[text]);
  }
  for (const element of document.querySelectorAll('[aria-label], [alt], [placeholder]')) {
    for (const key of ['aria-label', 'alt', 'placeholder']) {
      const value = element.getAttribute(key);
      if (value && Object.hasOwn(arabic, value)) element.setAttribute(key, t(value));
    }
  }
  document.title = t(document.title);
  const description = document.querySelector('meta[name="description"]');
  description.content = document.querySelector('#size-finder')
    ? 'دليل المشرف لمقاسات العبايات، مع جدول الأطوال وطريقة أخذ القياسات.'
    : 'تصفّحوا مجموعة العبايات والشيل لدى المشرف للخياطة والتطريز في دبي. استفسارات التجزئة والجملة.';
  const guideHeading = document.querySelector('.guide-heading h1');
  if (guideHeading) guideHeading.textContent = 'دليل مقاسات العبايات';
  for (const link of document.querySelectorAll('a[href]')) {
    const href = link.getAttribute('href');
    if (/^[\w-]+\.html(?:[?#]|$)/.test(href)) link.href = siteLink(href);
  }
}
for (const link of document.querySelectorAll('[data-language]')) {
  const choice = link.dataset.language;
  const url = new URL(location.href);
  url.searchParams.set('lang', choice);
  link.href = url.href;
  if (choice === language) link.setAttribute('aria-current', 'true');
  link.addEventListener('click', () => {
    const current = new URL(location.href);
    current.searchParams.set('lang', choice);
    link.href = current.href;
  });
}

